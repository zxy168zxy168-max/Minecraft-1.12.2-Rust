#[cfg(test)]
mod tests {
    use super::*;
    use crate::net::minecraft::nbt::NBTTagCompound::NBTTagCompound;

    fn item(item_id: i16, damage: i16, tag: Option<NBTTagCompound>) -> ItemStack {
        ItemStack {
            itemId: item_id,
            count: 1,
            itemDamage: damage,
            tagCompound: tag,
        }
    }

    #[test]
    fn leather_and_map_nbt_paths_match_vanilla() {
        let mut display = NBTTagCompound::new();
        display.setInteger("color", 0x123456);
        let mut root = NBTTagCompound::new();
        root.setCompoundTag("display", display);
        assert_eq!(leather_color(&item(298, 0, Some(root))), 0x123456);

        let mut display = NBTTagCompound::new();
        display.setInteger("MapColor", 0xABCDEF);
        let mut root = NBTTagCompound::new();
        root.setCompoundTag("display", display);
        assert_eq!(
            filled_map_color(&item(358, 0, Some(root))),
            -16_777_216_i32 | 0xABCDEF
        );
    }

    #[test]
    fn potion_custom_color_and_custom_effect_weighting_match_potion_utils() {
        let mut root = NBTTagCompound::new();
        root.setInteger("CustomPotionColor", 0x135724);
        assert_eq!(potion_color(&item(373, 0, Some(root))), 0x135724);

        let effects = [
            PotionColorEffect {
                color: 0xFF0000,
                amplifier: 0,
                showParticles: true,
            },
            PotionColorEffect {
                color: 0x0000FF,
                amplifier: 1,
                showParticles: true,
            },
        ];
        assert_eq!(potion_effect_list_color(&effects), 0x5500AA);
    }

    #[test]
    fn registry_tables_are_complete_for_vanilla_item_colors() {
        assert_eq!(POTION_TYPE_COLORS.len(), 37);
        assert_eq!(ENTITY_EGG_COLORS.len(), 43);
    }
}
