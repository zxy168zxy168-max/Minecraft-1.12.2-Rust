use crate::net::minecraft::world::ColorizerGrass::ColorizerGrass;

/// MCP 1.12.2 `ItemColors` registrations used by `RenderItem`.
///
/// The handler selection, tint-index rules, NBT paths and vanilla registry
/// colours mirror `ItemColors.init`, `PotionUtils.func_190932_c`,
/// `ItemArmor.getColor`, `ItemFireworkCharge.getExplosionTag`,
/// `ItemMonsterPlacer.func_190908_h`, and `ItemMap.func_190907_h`.
#[derive(Debug, Clone)]
pub struct ItemColors {
    inventoryGrassColor: i32,
}

impl ItemColors {
    pub const DEFAULT_COLOR: i32 = -1;

    pub fn new(grass: &ColorizerGrass) -> Self {
        Self {
            inventoryGrassColor: grass.getGrassColor(0.5, 1.0),
        }
    }

    pub fn getColorFromItemstack(&self, stack: &ItemStack, tintIndex: i32) -> i32 {
        if stack.isEmpty() {
            return Self::DEFAULT_COLOR;
        }
        match stack.itemId {
            // Items.LEATHER_HELMET/CHESTPLATE/LEGGINGS/BOOTS.
            298..=301 => {
                if tintIndex > 0 {
                    Self::DEFAULT_COLOR
                } else {
                    leather_color(stack)
                }
            }
            // Blocks.DOUBLE_PLANT. Only double grass and double fern are tinted.
            175 => match stack.itemDamage & 7 {
                2 | 3 => self.inventoryGrassColor,
                _ => Self::DEFAULT_COLOR,
            },
            // Items.FIREWORK_CHARGE.
            402 => {
                if tintIndex == 1 {
                    firework_charge_color(stack)
                } else {
                    Self::DEFAULT_COLOR
                }
            }
            // Items.POTIONITEM, Items.SPLASH_POTION, Items.LINGERING_POTION.
            373 | 438 | 441 => {
                if tintIndex > 0 {
                    Self::DEFAULT_COLOR
                } else {
                    potion_color(stack)
                }
            }
            // Items.SPAWN_EGG.
            383 => spawn_egg_color(stack, tintIndex),
            // ItemBlock registrations in ItemColors.init.
            2 | 18 | 31 | 106 | 111 | 161 => self.block_item_color(stack),
            // Items.TIPPED_ARROW.
            440 => {
                if tintIndex == 0 {
                    potion_color(stack)
                } else {
                    Self::DEFAULT_COLOR
                }
            }
            // Items.FILLED_MAP.
            358 => {
                if tintIndex == 0 {
                    Self::DEFAULT_COLOR
                } else {
                    filled_map_color(stack)
                }
            }
            _ => Self::DEFAULT_COLOR,
        }
    }

    fn block_item_color(&self, stack: &ItemStack) -> i32 {
        match stack.itemId {
            // Blocks.GRASS: BlockColors' null-world inventory fallback.
            2 => self.inventoryGrassColor,
            // Blocks.TALLGRASS: dead bush is white; grass and fern use grass colormap.
            31 => {
                if stack.itemDamage & 3 == 0 {
                    0xFF_FFFF
                } else {
                    self.inventoryGrassColor
                }
            }
            // Blocks.VINE.
            106 => ColorizerFoliage::getFoliageColorBasic(),
            // Blocks.LEAVES: oak/jungle basic, spruce/birch fixed.
            18 => match stack.itemDamage & 3 {
                1 => ColorizerFoliage::getFoliageColorPine(),
                2 => ColorizerFoliage::getFoliageColorBirch(),
                _ => ColorizerFoliage::getFoliageColorBasic(),
            },
            // Blocks.LEAVES2.
            161 => ColorizerFoliage::getFoliageColorBasic(),
            // Blocks.WATERLILY null-world inventory fallback.
            111 => 7_455_580,
            _ => Self::DEFAULT_COLOR,
        }
    }
}

fn leather_color(stack: &ItemStack) -> i32 {
    let Some(root) = &stack.tagCompound else {
        return 10_511_680;
    };
    if !root.hasKeyWithType("display", TAG_COMPOUND) {
        return 10_511_680;
    }
    let display = root.getCompoundTag("display");
    if display.hasKeyWithType("color", TAG_INT) {
        display.getInteger("color")
    } else {
        10_511_680
    }
}

fn firework_charge_color(stack: &ItemStack) -> i32 {
    let Some(root) = &stack.tagCompound else {
        return 9_079_434;
    };
    if !root.hasKeyWithType("Explosion", TAG_COMPOUND) {
        return 9_079_434;
    }
    let explosion = root.getCompoundTag("Explosion");
    let Some(NBTBase::IntArray(colors)) = explosion.getTag("Colors") else {
        return 9_079_434;
    };
    if colors.len() == 1 {
        return colors[0];
    }
    // Vanilla assumes a non-empty array here. Network/NBT data generated by
    // ItemFireworkCharge satisfies that invariant; retain a safe fallback for
    // malformed third-party server data rather than panicking on division by 0.
    if colors.is_empty() {
        return 9_079_434;
    }
    let mut red = 0_i64;
    let mut green = 0_i64;
    let mut blue = 0_i64;
    for color in colors {
        red += ((color & 0xFF_0000) >> 16) as i64;
        green += ((color & 0x00_FF00) >> 8) as i64;
        blue += (color & 0x00_00FF) as i64;
    }
    let length = colors.len() as i64;
    ((red / length) as i32) << 16 | ((green / length) as i32) << 8 | (blue / length) as i32
}

fn potion_color(stack: &ItemStack) -> i32 {
    let tag = stack.tagCompound.as_ref();
    if let Some(tag) = tag {
        if tag.hasKeyWithType("CustomPotionColor", 99) {
            return tag.getInteger("CustomPotionColor");
        }
    }

    let potion_name = tag
        .filter(|tag| tag.hasKeyWithType("Potion", TAG_STRING))
        .map(|tag| normalize_resource_location(&tag.getString("Potion")))
        .unwrap_or_else(|| "minecraft:empty".to_owned());

    // PotionUtils returns the special EMPTY colour before merging custom
    // potion effects.
    if potion_name == "minecraft:empty" || potion_type_color(&potion_name).is_none() {
        return 16_253_176;
    }

    let mut effects = Vec::<PotionColorEffect>::new();
    if let Some((potion_id, amplifier)) = potion_type_effect(&potion_name) {
        if let Some(color) = potion_effect_color(potion_id) {
            effects.push(PotionColorEffect {
                color,
                amplifier,
                showParticles: true,
            });
        }
    }

    if let Some(tag) = tag {
        if tag.hasKeyWithType("CustomPotionEffects", TAG_LIST) {
            let custom = tag.getTagList("CustomPotionEffects", TAG_COMPOUND);
            for index in 0..custom.tagCount() {
                let effect = custom.getCompoundTagAt(index);
                let potion_id = effect.getByte("Id") as i32;
                let Some(color) = potion_effect_color(potion_id) else {
                    continue;
                };
                let amplifier = (effect.getByte("Amplifier") as i32).max(0);
                let show_particles = if effect.hasKeyWithType("ShowParticles", 1) {
                    effect.getBoolean("ShowParticles")
                } else {
                    true
                };
                effects.push(PotionColorEffect {
                    color,
                    amplifier,
                    showParticles: show_particles,
                });
            }
        }
    }

    if effects.is_empty() {
        // WATER/MUNDANE/THICK/AWKWARD have no effects but are not EMPTY.
        return potion_type_color(&potion_name).unwrap_or(3_694_022);
    }
    potion_effect_list_color(&effects)
}

#[derive(Debug, Clone, Copy)]
struct PotionColorEffect {
    color: i32,
    amplifier: i32,
    showParticles: bool,
}

fn potion_effect_list_color(effects: &[PotionColorEffect]) -> i32 {
    let mut red = 0.0_f32;
    let mut green = 0.0_f32;
    let mut blue = 0.0_f32;
    let mut weight = 0_i32;
    for effect in effects
        .iter()
        .copied()
        .filter(|effect| effect.showParticles)
    {
        let effect_weight = effect.amplifier + 1;
        red += (effect_weight * ((effect.color >> 16) & 0xFF)) as f32 / 255.0;
        green += (effect_weight * ((effect.color >> 8) & 0xFF)) as f32 / 255.0;
        blue += (effect_weight * (effect.color & 0xFF)) as f32 / 255.0;
        weight += effect_weight;
    }
    if weight == 0 {
        0
    } else {
        ((red / weight as f32 * 255.0) as i32) << 16
            | ((green / weight as f32 * 255.0) as i32) << 8
            | (blue / weight as f32 * 255.0) as i32
    }
}

fn potion_type_effect(name: &str) -> Option<(i32, i32)> {
    let path = name.strip_prefix("minecraft:").unwrap_or(name);
    let amplifier = if path.starts_with("strong_") { 1 } else { 0 };
    let base = path
        .strip_prefix("long_")
        .or_else(|| path.strip_prefix("strong_"))
        .unwrap_or(path);
    let id = match base {
        "night_vision" => 16,
        "invisibility" => 14,
        "leaping" => 8,
        "fire_resistance" => 12,
        "swiftness" => 1,
        "slowness" => 2,
        "water_breathing" => 13,
        "healing" => 6,
        "harming" => 7,
        "poison" => 19,
        "regeneration" => 10,
        "strength" => 5,
        "weakness" => 18,
        "luck" => 26,
        _ => return None,
    };
    Some((id, amplifier))
}

